  <script>
    (function () {
      const slides = document.querySelectorAll('.hero-slide');
      const dots = document.querySelectorAll('.hero-dot');
      if (!slides.length) return;
      let sIdx = 0;
      window.showSlide = function (n) {
        sIdx = (n + slides.length) % slides.length;
        slides.forEach((el, i) => {
          el.classList.toggle('opacity-100', i === sIdx);
          el.classList.toggle('z-10', i === sIdx);
          el.classList.toggle('opacity-0', i !== sIdx);
          el.classList.toggle('z-0', i !== sIdx);
          el.classList.toggle('pointer-events-none', i !== sIdx);
        });
        dots.forEach((d, i) => {
          d.className = i === sIdx
            ? 'hero-dot h-2.5 rounded-full transition-all w-8 bg-amber-400'
            : 'hero-dot h-2.5 rounded-full transition-all w-2.5 bg-white/50 hover:bg-white/80';
        });
      };
      window.moveHeroSlide = function (step) { window.showSlide(sIdx + step); };
      window.goToHeroSlide = function (idx) { window.showSlide(idx); };
      setInterval(() => window.moveHeroSlide(1), 5000);
    })();

    const menuToggle = document.getElementById('menuToggle');
    const navMenu = document.getElementById('navMenu');
    const submenuItems = document.querySelectorAll('.has-submenu');
    if (menuToggle && navMenu) {
      menuToggle.addEventListener('click', () => navMenu.classList.toggle('open'));
    }
    submenuItems.forEach((item) => {
      const link = item.querySelector('.nav-link');
      link.addEventListener('click', (e) => {
        if (window.innerWidth < 1024) {
          e.preventDefault();
          item.classList.toggle('submenu-open');
        }
      });
    });

    function showToast(msg) {
      const toast = document.getElementById('diccai-toast');
      const label = document.getElementById('diccai-toast-msg');
      if (!toast || !label) return;
      label.textContent = msg;
      toast.classList.remove('hidden');
      clearTimeout(window._toastTimer);
      window._toastTimer = setTimeout(() => toast.classList.add('hidden'), 3500);
    }

    function handleContactSubmit(e) {
      e.preventDefault();
      showToast('Thank you! Your inquiry has been received by our Pune office.');
      e.target.reset();
    }
  </script>
